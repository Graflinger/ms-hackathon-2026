async def test_sse_drains_multiple_batches_before_terminal_close(client, app):
    chat = (await client.post("/api/v1/chat-sessions", json={"agent_revision": "fixed"})).json()
    async with app.state.db.write() as session:
        for index in range(205):
            session.add(Event(stream="chat:" + chat["id"], kind="message", payload={"index": index}))
    path = f"/api/v1/chat-sessions/{chat['id']}/events"
    response = await client.get(path)
    ids = [int(line[4:]) for line in response.text.splitlines() if line.startswith("id: ")]
    assert len(ids) == 205 and ids == sorted(set(ids))
    resumed = await client.get(path, headers={"Last-Event-ID": str(ids[99])})
    assert resumed.text.count("event: message") == 105
    assert (await client.get(path + "?after=9999999999999999999999999999")).status_code == 422


@pytest.mark.parametrize(
    "peer,host,origin",
    [
        ("127.0.0.1", "127.0.0.1:8000", "http://localhost:5173"),
        ("::1", "[::1]:8000", "http://[::1]:5173"),
        ("127.0.0.1", "localhost:8000", "http://127.0.0.1:5173"),
    ],
)
async def test_vite_proxy_local_origins(app, peer, host, origin):
    async with httpx.AsyncClient(
        transport=httpx.ASGITransport(app=app, client=(peer, 12345)), base_url="http://localhost"
    ) as client:
        response = await client.post(
            "/api/v1/chat-sessions",
            json={"agent_revision": "fixed"},
            headers={"host": host, "origin": origin, "sec-fetch-site": "same-origin"},
        )
        assert response.status_code == 201


async def test_disconnect_does_not_cancel_run(client, case_payload, monkeypatch):
    # The command is durable independently of opening or keeping an SSE connection.
    invoked = asyncio.Event()
    finish = asyncio.Event()

    async def delayed(case, revision, mode):
        invoked.set()
        await finish.wait()
        return await demo_run_case(case, revision=revision, mode=mode)

    monkeypatch.setattr("goldenloop_api.runner.run_case", delayed)
    _, release = await publish(client, case_payload)
    run = (
        await client.post(
            "/api/v1/evaluation-runs",
            json={"release_id": release["id"], "agent_revision": "fixed", "idempotency_key": "disconnect"},
        )
    ).json()
    await asyncio.wait_for(invoked.wait(), 2)
    stream_task = asyncio.create_task(client.get(f"/api/v1/evaluation-runs/{run['id']}/events"))
    await asyncio.sleep(0.02)
    stream_task.cancel()
    with pytest.raises(asyncio.CancelledError):
        await stream_task
    finish.set()
    result = await wait_for(client, f"/api/v1/evaluation-runs/{run['id']}")
    assert result["status"] == "completed" and result["gate"] == "pass"

async def test_chat_continues_persisted_answers_without_replaying_tools(client, app, monkeypatch):
    invocations = []

    async def observed(case, revision, mode):
        invocations.append([turn.user for turn in case.turns])
        return await demo_run_case(case, revision=revision, mode=mode)

    monkeypatch.setattr("goldenloop_api.runner.run_case", observed)
    chat = (await client.post("/api/v1/chat-sessions", json={"agent_revision": "fixed"})).json()
    path = f"/api/v1/chat-sessions/{chat['id']}"
    await client.post(path + "/messages", json={"content": "Look up C-123"})
    first = await wait_for(client, path)
    # Simulate an earlier agent build's generated answer. The persisted history is authoritative.
    async with app.state.db.write() as session:
        row = await session.get(ChatSession, chat["id"])
        row.messages = [row.messages[0], {**row.messages[1], "content": "Previously generated unique answer"}]
    await client.post(path + "/messages", json={"content": "Repeat the answer"})
    second = await wait_for(client, path)
    assert second["messages"][-1]["content"] == "From my previous answer: Previously generated unique answer"
    assert second["tool_calls"] == first["tool_calls"]
    await client.post(path + "/messages", json={"content": "Look up C-999"})
    third = await wait_for(client, path)
    assert invocations == [["Look up C-123"], ["Repeat the answer"], ["Look up C-999"]]
    assert [call["turn"] for call in third["tool_calls"]] == [0, 2]
    assert len({call["id"] for call in third["tool_calls"]}) == 2
    assert "C-999" in third["messages"][-1]["content"]
    assert third["messages"][:4] == second["messages"]



@pytest.mark.parametrize(
    "check",
    [
        {"kind": "unknown", "config": {}},
        {"kind": "content_contains", "config": {}},
        {"kind": "exact_match", "config": {"value": ""}},
        {"kind": "tool_required", "config": {"tool": "lookup_customer", "min": 0}},
        {"kind": "tool_required", "config": {"tool": "lookup_customer", "min": 2, "max": 1}},
        {"kind": "tool_forbidden", "config": {"tool": "lookup_customer", "max": 2}},
        {"kind": "tool_order", "config": {"tools": [""]}},
        {
            "kind": "tool_arguments",
            "config": {"tool": "lookup_customer", "path": "id", "operator": "bogus", "value": 1},
        },
        {"kind": "json_schema", "config": {"schema": {"type": "bogus"}}},
        {"kind": "json_schema", "config": {"schema": {"$ref": "https://example.com/schema"}}},
        {"kind": "judge", "config": {"rubric": "Correctness", "threshold": 2}},
        {"kind": "judge", "config": {"rubric": "", "threshold": 0.5}},
    ],
)
async def test_invalid_checks_stay_candidates(client, case_payload, check):
    case_payload["checks"].append({**check, "required": False})
    response = await client.post("/api/v1/cases", json={"case": case_payload})
    assert response.status_code == 201
    case_id = response.json()["case"]["id"]
    response = await client.post(f"/api/v1/cases/{case_id}/approve", json={"revision": 1, "reason": "Review"})
    assert response.status_code == 422, response.text
    record = (await client.get(f"/api/v1/cases/{case_id}")).json()
    assert record["status"] == "candidate" and record["reviewer"] is None
    response = await client.post(
        "/api/v1/dataset-releases",
        json={"name": "invalid", "case_ids": [case_id], "expected_revisions": {case_id: 1}},
    )
    assert response.status_code == 409


